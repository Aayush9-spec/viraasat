'use server';

/**
 * @fileOverview Multimodal AI flow to analyze an image of a handicraft and generate
 * a culturally grounded analysis of its visible characteristics, craft techniques,
 * and heritage significance using Google Gemini 1.5 Flash Vision.
 */

import { ai, isGeminiConfigured } from '@/ai/genkit';
import { z } from 'genkit';
import { getLanguageName } from '@/ai/languages';

const ALLOWED_MIME_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'image/jpg'];
const MAX_BASE64_LENGTH = 14 * 1024 * 1024; // ~10MB binary limit

const ImageCulturalStoryInputSchema = z.object({
  imageDataUri: z
    .string()
    .min(100, 'Image data URI too short')
    .refine((data) => data.startsWith('data:image/'), {
      message: 'Image must be a valid data URI starting with data:image/',
    })
    .describe(
      "Image data URI of the handicraft item. Must include a MIME type and use Base64 encoding. Expected format: 'data:<mimetype>;base64,<encoded_data>'."
    ),
  craftContext: z
    .string()
    .trim()
    .max(500, 'Context notes cannot exceed 500 characters')
    .optional()
    .describe('Optional artisan-provided hints such as craft name, known region, or materials.'),
  outputLanguage: z
    .string()
    .optional()
    .default('Hindi')
    .describe('Language in which to generate the cultural story analysis.'),
});

export type ImageCulturalStoryInput = z.infer<
  typeof ImageCulturalStoryInputSchema
>;

const ImageCulturalStoryOutputSchema = z.object({
  story: z
    .string()
    .describe(
      'A detailed, culturally accurate analysis of the handicraft item including visible materials, probable craft lineage, and cultural significance.'
    ),
  isAiGenerated: z
    .boolean()
    .optional()
    .default(true)
    .describe('Whether the story was generated by live Gemini vision inference.'),
});

export type ImageCulturalStoryOutput = z.infer<
  typeof ImageCulturalStoryOutputSchema
>;

/**
 * Server Action to generate a cultural story and visual analysis from an uploaded craft photo.
 * Adheres strictly to Next.js 'use server' constraints (exports only async functions).
 */
export async function generateImageCulturalStory(
  input: ImageCulturalStoryInput
): Promise<ImageCulturalStoryOutput> {
  // 1. Validate Input Data URI format and size
  const dataUri = input.imageDataUri;
  if (!dataUri || !dataUri.startsWith('data:image/')) {
    throw new Error('Invalid image format. Supported formats are JPEG, PNG, and WebP.');
  }

  if (dataUri.length > MAX_BASE64_LENGTH) {
    throw new Error('Image size exceeds the 10 MB limit. Please compress or resize the image.');
  }

  const mimeMatch = dataUri.match(/^data:(image\/[a-zA-Z0-9+-]+);base64,/);
  if (!mimeMatch) {
    throw new Error('Malformed image data URI. Missing valid MIME type or base64 encoding.');
  }

  const mimeType = mimeMatch[1].toLowerCase();
  if (!ALLOWED_MIME_TYPES.includes(mimeType)) {
    throw new Error(
      `Unsupported image format (${mimeType}). Please upload a JPEG, PNG, or WebP image.`
    );
  }

  // 2. Check server-side Gemini AI configuration
  if (!isGeminiConfigured()) {
    throw new Error(
      'Gemini Vision AI is offline: GEMINI_API_KEY is not configured on the server. Please add your key to Vercel or your environment variables.'
    );
  }

  const targetLang = getLanguageName(input.outputLanguage || 'Hindi');
  const contextNotes = input.craftContext ? `\nArtisan Context Notes: "${input.craftContext}"` : '';

  const systemPrompt = `You are a museum curator and master ethnographer of Indian living heritage and traditional handicrafts.

Examine the uploaded handicraft image carefully and provide an authentic, well-structured cultural analysis in ${targetLang}.

Analyze and structure your response with the following sections:
1. **Visual Identification (दृश्य पहचान)**: What object is shown? Describe visible shapes, decorative patterns, colors, and motifs.
2. **Craftsmanship & Materials (शिल्प विधि एवं सामग्री)**: Identify apparent materials (e.g. natural river clay, brass alloy, mulberry silk, teakwood) and visible handcrafting techniques. State uncertainties where applicable.
3. **Regional Lineage & Tradition (क्षेत्रीय परंपरा)**: Where in India is this craft tradition historically nurtured? Mention prominent artisan clusters (e.g. Jaipur Blue Pottery, Varanasi Zari, Bastar Dhokra, Molela Terracotta) as probable lineages.
4. **Cultural Significance (सांस्कृतिक महत्व)**: What purpose, sacred symbolism, festival connection, or daily living role does this craft hold?
5. **Authenticity & Heritage Preservation (धरोहर संरक्षण)**: Why is continuing this handmade tradition vital for rural Indian livelihoods and intangible cultural heritage?

Strict Accuracy & Provenance Guidelines:
- Do NOT invent specific artisan names, fake workshop addresses, or verified GI certificates not proven by the image.
- Clearly separate what is directly visible from what is a plausible cultural interpretation.
- Write in engaging, respectful, flowing narrative prose in ${targetLang} (approx 200-300 words).
- If the image is not a recognizable craft, explain politely what is visible and suggest uploading a clearer photo of the handmade item.${contextNotes}`;

  try {
    const response = await ai.generate({
      prompt: [
        {
          media: {
            url: dataUri,
          },
        },
        {
          text: systemPrompt,
        },
      ],
    });

    const text = response.text?.trim();
    if (!text) {
      throw new Error('Gemini vision model returned an empty response.');
    }

    return {
      story: text,
      isAiGenerated: true,
    };
  } catch (err: unknown) {
    console.error('generateImageCulturalStory error:', err);
    const msg = err instanceof Error ? err.message : String(err);

    if (msg.includes('RESOURCE_EXHAUSTED') || msg.includes('429')) {
      throw new Error('AI rate limit reached. Please wait a few moments and try again.');
    }
    if (msg.includes('INVALID_ARGUMENT') || msg.includes('API key not valid')) {
      throw new Error('Invalid Gemini API credentials. Please check your GEMINI_API_KEY setting.');
    }

    throw new Error(`Image analysis failed: ${msg.slice(0, 160)}`);
  }
}
