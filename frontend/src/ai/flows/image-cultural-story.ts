function isExplicitNonHandicraftContext(context: string): boolean {
  const lower = context.toLowerCase();
  return NON_HANDICRAFT_TERMS.some(term => {
    const regex = new RegExp(`\\b${term}\\b`, 'i');
    return regex.test(lower);
  });
}

