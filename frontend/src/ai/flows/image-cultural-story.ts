function findCraftByContext(context?: string): CraftArchiveEntry | null {
  if (!context || !context.trim()) return null;
  const clean = context.toLowerCase().trim();
  for (const craft of CRAFT_ARCHIVE) {
    if (craft.names.some(name => clean.includes(name))) {
      return craft;
    }
  }
  return null;
}

