  'car', 'automobile', 'vehicle', 'bike', 'motorcycle', 'truck',
  'phone', 'mobile', 'iphone', 'android', 'smartphone', 'laptop', 'computer',
  'macbook', 'tablet', 'gadget', 'electronics', 'television', 'tv',
