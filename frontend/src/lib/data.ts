export function getLocalProducts(): Product[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem('viraasat_local_products');
    if (!raw) return [];
    const items = JSON.parse(raw);
    if (!Array.isArray(items)) return [];
    // Filter out any stale mock catalog seeds that may have been saved with old inflated prices in earlier testing
    const validItems = items.filter((r: any) => {
      if (!r || typeof r !== 'object') return false;
      if (typeof r.id === 'string' && (r.id.startsWith('prod-') || r.id.startsWith('f83a21b4'))) return false;
      if (r.name && (r.name.includes('Channapatna') || r.name.includes('Blue Pottery') || r.name.includes('Madhubani') || r.name.includes('Pashmina') || r.name.includes('Dancing Bull'))) return false;
      return true;
    });
    return validItems.map((r: any) => ({
      id: r.id || `local-prod-${Math.random()}`,
      artisanId: r.artisan_id || r.artisanId || 'artisan-1',
      name: r.name || 'Untitled Craft',
      description: r.description || '',
      tagline: r.tagline || '',
      category: r.category || 'Home Decor',
      price: Number(r.price) || 0,
      currency: r.currency || 'INR',
      stock: r.stock ?? 10,
      images: (() => {
        if (Array.isArray(r.images) && r.images.length > 0 && !r.images[0].includes("1610701596007")) {
          return r.images;
        }
        const n = (r.name || '').toLowerCase();
        if (n.includes('diya') || n.includes('deepam') || n.includes('lamp') || n.includes('candle')) {
          return ['/images/products/clean/handcrafted-terracotta-diya.jpg'];
        }
        if (n.includes('channapatna') || n.includes('toy') || n.includes('train')) {
          return ['/images/products/clean/channapatna-wooden-toy-train.jpg'];
        }
        if (n.includes('blue pottery') || n.includes('pottery') || n.includes('vase') || n.includes('urn')) {
          return ['/images/products/clean/jaipur-blue-pottery-urn.jpg'];
        }
        if (n.includes('pashmina') || n.includes('shawl') || n.includes('sozni')) {
          return ['/images/products/clean/kashmiri-sozni-pashmina-shawl.jpg'];
        }
        if (n.includes('brass') || n.includes('dhokra') || n.includes('metal')) {
          return ['/images/products/clean/moradabad-brass-ganesh-idol.jpg'];
        }
        if (n.includes('carpet') || n.includes('dhurrie')) {
          return ['/images/products/clean/bhadohi-hand-knotted-carpet.jpg'];
        }
        if (n.includes('saree') || n.includes('silk') || n.includes('chikankari')) {
          return ['/images/products/clean/banarasi-silk-saree.jpg'];
        }
        return ['/images/products/clean/handcrafted-terracotta-diya.jpg'];
      })(),
      region: r.region || 'Rajasthan',
      originalLanguage: r.originalLanguage || r.original_language,
      englishDescription: r.englishDescription || r.english_description,
      descriptions: r.descriptions || r.ai_insights?.descriptions || r.aiInsights?.descriptions,
      aiInsights: r.ai_insights || r.aiInsights,
      isActive: r.isActive ?? true,
      status: (r.status || 'active') as 'active' | 'archived',
      createdAt: r.createdAt || new Date().toISOString(),
      updatedAt: r.updatedAt || new Date().toISOString(),
    }));
  } catch (e) {
    console.warn('Failed to parse viraasat_local_products from localStorage:', e);
    return [];
  }
}

export function saveLocalProduct(localItem: any): Product[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem('viraasat_local_products');
    const localProducts = raw ? JSON.parse(raw) : [];
    const idx = localProducts.findIndex((p: any) => p.id === localItem.id);
    if (idx >= 0) {
      localProducts[idx] = { ...localProducts[idx], ...localItem };
    } else {
      localProducts.unshift(localItem);
    }
    localStorage.setItem('viraasat_local_products', JSON.stringify(localProducts));

    // Dispatch both standard and custom storage events for same-window listeners
    window.dispatchEvent(new Event('storage'));
    window.dispatchEvent(new CustomEvent('viraasat_products_updated'));

    return getLocalProducts();
  } catch (e) {
    console.warn('Failed to save product to localStorage:', e);
    return getLocalProducts();
  }
}



