def update_locales():
    langs = ["en", "hi", "ta", "bn", "te", "mr", "gu", "kn", "ml", "pa", "ur", "or", "as"]
    for lang in langs:
        file_path = os.path.join(LOCALES_DIR, f"{lang}.json")
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        if "download" not in data:
            data["download"] = {}
        
        for k, lang_map in DOWNLOAD_KEYS.items():
            data["download"][k] = lang_map.get(lang, lang_map["en"])
        
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=4)
        print(f"Updated {lang}.json with download keys.")

if __name__ == "__main__":
    update_locales()
